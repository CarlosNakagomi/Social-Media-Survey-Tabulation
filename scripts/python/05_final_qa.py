qa_rows = []

for _, row in plan.iterrows():

    table_id = row["table_id"]
    platform = row["platform"]
    variable = row["variable"]
    weight = row["weight"]
    universe_expression = row["universe"]

    universe_mask = parse_universe(
        universe_expression
    )

    eligible = df.loc[
        universe_mask
    ].copy()

    eligible_n = len(eligible)

    valid_mask = (
        eligible[variable].isin(
            VALID_RESPONSES
        )
        &
        eligible[weight].notna()
    )

    valid = eligible.loc[
        valid_mask
    ].copy()

    valid_n = len(valid)

    special_or_invalid_n = (
        eligible_n - valid_n
    )

    weighted_base = (
        valid[weight].sum()
    )

    percentages = []

    if weighted_base > 0:

        for response in VALID_RESPONSES:

            numerator = valid.loc[
                valid[variable] == response,
                weight,
            ].sum()

            percentages.append(
                numerator
                / weighted_base
                * 100
            )

    percentage_sum = (
        sum(percentages)
        if percentages
        else np.nan
    )

    percentage_qa = (
        "PASS"
        if (
            not pd.isna(percentage_sum)
            and abs(
                percentage_sum - 100
            ) <= 0.2
        )
        else "FAIL"
    )

    qa_rows.append({
        "table_id": table_id,
        "platform": platform,
        "variable": variable,
        "weight": weight,
        "eligible_n": eligible_n,
        "valid_n": valid_n,
        "special_or_invalid_n":
            special_or_invalid_n,
        "weighted_base": weighted_base,
        "percentage_qa":
            percentage_qa,
        "measure":
            get_measure_label(variable),
        "universe":
            universe_expression,
    })


