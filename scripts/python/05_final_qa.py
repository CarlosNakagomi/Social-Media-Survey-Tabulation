def parse_universe(expression):

    pattern = (
        r"^\s*([A-Za-z0-9_]+)"
        r"\s*==\s*(-?\d+(?:\.\d+)?)\s*$"
    )

    match = re.match(
        pattern,
        str(expression)
    )

    if not match:
        raise ValueError(
            "Unsupported universe expression: "
            f"{expression}"
        )

    variable = match.group(1)
    value = float(match.group(2))

    if variable not in df.columns:
        raise KeyError(
            "Universe variable not found: "
            f"{variable}"
        )

    return (
        pd.to_numeric(
            df[variable],
            errors="coerce",
        )
        == value
    )


def get_measure_label(variable):

    match = re.search(
        r"WHY_([a-g])_W144$",
        str(variable),
    )

    if not match:
        raise ValueError(
            "Cannot determine WHY item: "
            f"{variable}"
        )

    return MEASURE_LABELS[
        match.group(1)
    ]


def kish_effective_n(weights):

    weights = pd.to_numeric(
        weights,
        errors="coerce",
    ).dropna()

    if len(weights) == 0:
        return np.nan

    sum_w = weights.sum()
    sum_w2 = (weights ** 2).sum()

    if sum_w2 == 0:
        return np.nan

    return (
        sum_w ** 2
        / sum_w2
    )


def classify_base(n):
    """
    Return presentation value + QA flag.
    """

    n = int(n)

    if n < VERY_SMALL_BASE_LIMIT:
        return (
            f"{n}**",
            "VERY SMALL BASE",
        )

    if n < SMALL_BASE_LIMIT:
        return (
            f"{n}*",
            "SMALL BASE",
        )

    return (
        str(n),
        "OK",
    )


